def load_done_ok(path: pathlib.Path) -> set:
    if not path.exists():
        return set()
    done = set()
    for line in path.read_text(encoding="utf-8").split("\n"):
        if not line.strip():
            continue
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if r.get("call_id") and not r.get("error"):
            done.add(r["call_id"])
    return done


def seal_call(call_id, body, ledger: pathlib.Path, extra=None):
    """jc.call_and_seal with one adaptation: only SUCCESSFUL call_ids resume-skip
    (a failed row is a receipt, not a verdict -- re-running the command retries
    it; duplicates remain impossible within a run)."""
    if call_id in load_done_ok(ledger):
        print("skip " + call_id + " (already sealed)")
        return {"skipped": True, "call_id": call_id}
    qmap_hash = jc.sha(json.dumps(body.get("questions") or {}, sort_keys=True))
    print("call " + call_id + " (" + str(len(body.get("questions") or {}))
          + " questions, state " + str(len(body.get("state") or "")) + " chars) ...",
          flush=True)
    t0 = time.time()
    r = jc.http_post(body)
    elapsed_ms = int((time.time() - t0) * 1000)
    row = {
        "call_id": call_id,
        "model_requested": jc.MODEL,
        "model_served": None,
        "state_hash": jc.sha(body.get("state") or ""),
        "state_chars": len(body.get("state") or ""),
        "questions_hash": qmap_hash,
        "question_count": len(body.get("questions") or {}),
        "elapsed_ms": elapsed_ms,
        "sealed_at": jc.now(),
        "endpoint": jc.ENDPOINT,
        "parse_method": "systemone-json-direct (answers read from response "
                        "object at .answers, no text parsing)",
    }
    if extra:
        row.update(extra)
    if r["ok"]:
        j = r["j"]
        row.update({
            "model_served": j.get("model"),
            "response_raw": j,
            "usage": j.get("usage"),
            "usd_est": round(jc.spend_of(j.get("usage")), 8),
        })
        jc.append_row(ledger, row)
        print("  sealed: served " + str(j.get("model")) + " | "
              + str(len(j.get("answers") or {})) + " answers | " + str(elapsed_ms)
              + "ms | usage " + json.dumps(j.get("usage")), flush=True)
        return {"ok": True, "row": row}
    row.update({"error": r["error"], "attempts": jc.MAX_ATTEMPTS})
    jc.append_row(ledger, row)
    print("  FAILED: " + str(r["error"]) + " -- failure receipted", flush=True)
    return {"ok": False, "row": row}


