def _skip_rel(rel: str) -> bool:
    parts = pathlib.PurePosixPath(rel).parts
    if any(part in SKIP_DIRS for part in parts):
        return True
    return (len(parts) >= 2 and parts[0] == "docs"
            and parts[1] in SKIP_DOC_SUBDIRS)

