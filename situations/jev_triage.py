def parse_stage1(answers, fid):
    """Extract one finding's stage-1 draft from a seat's answers map."""
    out = {}
    a = answers.get(fid + "__class")
    if a and a.get("type") == "choice":
        out["class"] = a.get("choice")
        out["class_confidence"] = a.get("confidence")
        out["class_probabilities"] = a.get("probabilities")
    a = answers.get(fid + "__actionable")
    if a and a.get("type") == "noul":
        out["actionable_noul"] = a.get("noul")
    a = answers.get(fid + "__severity")
    if a and a.get("type") == "score":
        out["severity_score"] = a.get("score")
        out["severity_confidence"] = a.get("confidence")
    return out


def final_class_of(draft_class, grounded_choice, grounded_conf, route):
    if route == "mechanical":
        return "fabricated_or_misstated"
    if route == "human_flag":
        return "human_flag"
    # route == "jev", conf >= gate
    if grounded_choice == "fabricated_or_misstated":
        return "fabricated_or_misstated"
    if grounded_choice == "yes_true":
        return draft_class if draft_class in DRAFT_CLASSES else "human_flag"
    if grounded_choice == "cannot_settle":
        if draft_class in ("verified_new", "plausible_unverified") or not draft_class:
            return "plausible_unverified"
        return draft_class
    return "human_flag"


def grounded_verdict_of(ans):
    """One grounded Choice answer -> (route, choice, conf, detail_lines).
    The earned loop's law: conf < CONF_GATE routes to a human instead of a
    verdict; a missing answer is fail-closed."""
    if ans is None:
        return ("human_flag", None, None,
                ["grounded answer missing (fail-closed)"])
    conf = ans.get("confidence")
    detail = ["verdict: " + str(ans.get("choice")) + " (conf " + str(conf)
              + ", probabilities " + json.dumps(ans.get("probabilities")) + ")"]
    if conf is None or conf < CONF_GATE:
        detail.append("confidence below the " + str(CONF_GATE)
                      + " gate -- escalated to a human (the earned loop's law)")
        return ("human_flag", ans.get("choice"), conf, detail)
    return ("jev", ans.get("choice"), conf, detail)


