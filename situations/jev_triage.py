def approx_marked(text, idx):
    """True if the number ending at idx is preceded by an approximation marker."""
    return bool(APPROX_BEFORE.search(text[:idx]))


def clean_paths(text, paths):
    """Post-filter for arm_b's RE_PATH matches: a match immediately followed by
    an identifier char is NOT a cited path -- the extension alternation's
    single-letter `.c`/`.h` members can bite a prefix off a longer suffix
    (e.g. 'receipts/E-Q16.chain' extracts as 'receipts/E-Q16.c'). A citation
    must end at the extension (the arm_b vocabulary of cited artifacts)."""
    out = []
    for p in paths:
        for m in re.finditer(re.escape(p), text):
            end = m.end()
            if end >= len(text) or not (text[end].isalnum() or text[end] == "_"):
                out.append(p)
                break
    return out


def mechanical_pass_finding(text):
    """arm_b.mechanical_pass adapted for standing triage (see module docstring).

    Returns {anchors, failures, facts, verdict, existing_files}.
    """
    a = arm_b.extract_anchors(text)
    a["paths"] = clean_paths(text, a["paths"])
    failures = []
    facts = []

    existing = arm_b.cited_existing_files(a["paths"], a.get("barenames", []))
    for p in [p for p in a["paths"] if p not in existing]:
        failures.append({
            "class": "invented_file",
            "detail": "cited path " + p + " does not exist in the repository",
        })
    if a["paths"]:
        facts.append("cited paths: " + "; ".join(
            p + (" (exists)" if p in existing else " (MISSING)") for p in a["paths"]))

    for p in existing:
        if p.endswith(".jsonl"):
            fp = REPO / p
            if fp.exists():
                rows = [l for l in fp.read_text(encoding="utf-8").split("\n") if l.strip()]
                facts.append("row-count of " + p + " = " + str(len(rows)) + " (computed)")

    for h in a["hexes"]:
        total, per = needle_hits(h)
        if total:
            facts.append("sha " + h[:12] + "... found in: "
                         + ", ".join(rel for _, rel, _ in per[:4]))
        else:
            n_files = len(repo_texts())
            failures.append({
                "class": "sha_not_in_repo",
                "detail": "sha " + h + " appears nowhere in the repository "
                          "(corpus walk, " + str(n_files) + " files; situations/ "
                          "and docs/{discussions,research}/ excluded as "
                          "meta-record, not artifacts)",
            })
            facts.append("sha " + h[:12] + "... NOT FOUND repo-wide")

    for n, f in a["rowofs"]:
        fp = REPO / f
        if fp.exists():
            rows = [l for l in fp.read_text(encoding="utf-8").split("\n") if l.strip()]
            if n > len(rows):
                failures.append({
                    "class": "row_id_out_of_range",
                    "detail": "row " + str(n) + " of " + f + " is out of range: the "
                              "chain carries " + str(len(rows)) + " rows",
                })

    # numbers, repo-wide (see docstring for the adaptation)
    seen = set()
    for num in a["numbers"]:
        if num in seen:
            continue
        seen.add(num)
        total, per = needle_hits(num)
        if total:
            facts.append("number " + num + " found repo-wide in: "
                         + ", ".join(rel for _, rel, _ in per[:4]))
        else:
            idx = text.find(num)
            if approx_marked(text, idx):
                facts.append("number " + num + " NOT FOUND repo-wide (exempt from "
                             "hard fail: marked approximate/derived)")
            else:
                failures.append({
                    "class": "number_not_in_repo",
                    "detail": "number " + num + " appears NOWHERE in the repository "
                              "(corpus walk; situations/ and docs/{discussions,"
                              "research}/ excluded) though the finding states it "
                              "as a sealed value",
                })
                facts.append("number " + num + " NOT FOUND repo-wide")

    # invented CLI flags proposed against cited repo scripts (code decides)
    for p in existing:
        if not p.endswith(SCRIPT_EXTS):
            continue
        src = (REPO / p).read_text(encoding="utf-8")
        for m in re.finditer(re.escape(p), text):
            tail = text[m.end():m.end() + 220]
            for fl in RE_FLAG.findall(tail):
                if fl not in src:
                    failures.append({
                        "class": "invented_flag",
                        "detail": "falsifier proposes '" + fl + "' against " + p
                                  + "; that flag appears nowhere in the script's "
                                  "source (repo walk) -- an invented interface",
                    })
                    facts.append("flag " + fl + " NOT FOUND in cited script " + p)

    verdict = "fabricated" if failures else "pass"
    return {"anchors": a, "failures": failures, "facts": facts,
            "verdict": verdict, "existing_files": existing}


def _eq_tokens(rel):
    """path -> filename token set, hyphens normalized: 'e_q13_results.json'
    -> {e, q13, results, json}; 'eq9_sweep_results.json' -> {eq9, ...}."""
    name = rel.lower().replace("-", "_")
    return set(re.sub(r"[^a-z0-9]+", " ", name).split())


def files_for_eq(n):
    """Files belonging to experiment E-Q<n>, derived from the outputs/
    receipts NAMING CONVENTITION (the registry's own layout -- not a
    hand-maintained artifact map; the defect-#7 lesson). Priority: sealed
    results JSON > stone chain > pre-registration > runner scripts/tips.
    Boundary-safe: q1 matches e_q1 but never e_q10."""
    want = {"q" + str(n), "eq" + str(n)}
    res, chain, prereg, other = [], [], [], []
    for rel in repo_texts():
        toks = _eq_tokens(rel)
        if not (toks & want):
            continue
        if rel.startswith("experiments/outputs/") and "results" in toks:
            res.append(rel)
        elif rel.startswith("receipts/") and rel.endswith(".jsonl"):
            chain.append(rel)
        elif rel.startswith("experiments/") and "pre" in toks:
            prereg.append(rel)
        else:
            other.append(rel)
    return sorted(res) + sorted(chain) + sorted(prereg) + sorted(other)


_CHAIN_CLAIM_MAP = None


def chain_claim_map():
    """claim token (C1..C5', R3..) -> E-Q number, read from the stone chain
    HEADERS' own claim/experiment wiring (the sealed record, regenerated by
    the registry -- drift-resistant by construction, no hand map)."""
    global _CHAIN_CLAIM_MAP
    if _CHAIN_CLAIM_MAP is None:
        m = {}
        for rel in sorted(repo_texts()):
            if not rel.endswith(".jsonl"):
                continue
            if not (rel.startswith("receipts/") or rel.startswith("crossimpl/receipts/")):
                continue
            try:
                head = json.loads(repo_texts()[rel].split("\n")[0])
            except (json.JSONDecodeError, IndexError):
                continue
            if head.get("kind") != "stone.header":
                continue
            eq = RE_EQID.search(str(head.get("experiment") or ""))
            if not eq:
                continue
            n = int(eq.group(1))
            for cm in re.finditer(r"\b([CR]\d)(?:(?:'|\u2019)(?![A-Za-z]))?\b",
                                  str(head.get("claim") or "")):
                tok = cm.group(1) + ("'" if cm.group(0)[-1] in "'\u2019" else "")
                m.setdefault(tok, n)
        _CHAIN_CLAIM_MAP = m
    return _CHAIN_CLAIM_MAP


def claim_ids_in(text):
    """Citation-style claim ids in text: C1, C3, C5', C5-prime, R3, ...
    A possessive ('C2's ...') is NOT a prime marker."""
    out = []
    for m in re.finditer(r"\b([CR]\d)(?:-prime|(?:(?:'|\u2019)(?![A-Za-z])))?\b", text):
        tok = m.group(1) + ("'" if len(m.group(0)) > len(m.group(1)) else "")
        if tok not in out:
            out.append(tok)
    return out


def _anchor_variants(tok):
    return (tok, tok.replace("-", "_"), tok.replace("_", "-"),
            tok.replace("-", ""), tok.replace("_", ""))


def section_for(path, anchors, why):
    """Window of `path` around the claim's best in-file anchor (arm_b
    locator semantics; whole file when small). Numbers may anchor location
    only when rarity-filtered repo-wide -- a 4,995-occurrence '100' must not
    drive location (the v1 lesson). The winning anchor is the one whose
    WINDOW covers the most distinct claim anchors, then the rarest in-file,
    then kind rank, then offset -- the v2 lesson: a count-1 tie between
    'adversarial' (file header) and 'zero-pollution' (the verdict tail)
    must resolve toward the window that actually carries the evidence."""
    raw = repo_texts()[path]
    if len(raw) <= WHOLE_FILE_MAX:
        return {"path": path, "window": raw,
                "method": why + "; whole file (" + str(len(raw)) + " chars)",
                "anchor_kind": "whole-file", "anchor": "-", "anchor_offset": 0}
    # the claim anchors that can score a window (variants tolerated)
    scorers = []
    for h in anchors.get("hexes") or []:
        scorers.append(h)
    for num in anchors.get("numbers") or []:
        total, _per = needle_hits(num)
        if 0 < total <= RARE_NUM_MAX_TOTAL:
            scorers.append(num)
    for tok in anchors.get("tokens") or []:
        scorers.append(tok)

    def window_score(start, end):
        seg = raw[start:end]
        n = 0
        for s in scorers:
            if any(v and v in seg for v in _anchor_variants(s)):
                n += 1
        return n

    cands = []  # (-window_score, in-file count, kind rank, offset, display)
    for h in anchors.get("hexes") or []:
        if h in raw:
            i = raw.find(h)
            st = max(0, i - arm_b.WINDOW_BEFORE)
            cands.append((-window_score(st, st + arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER),
                          raw.count(h), 0, i, h[:16]))
    for num in anchors.get("numbers") or []:
        total, _per = needle_hits(num)
        if 0 < total <= RARE_NUM_MAX_TOTAL and num in raw:
            i = raw.find(num)
            st = max(0, i - arm_b.WINDOW_BEFORE)
            cands.append((-window_score(st, st + arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER),
                          raw.count(num), 1, i, num))
    for tok in anchors.get("tokens") or []:
        best = None
        for v in _anchor_variants(tok):
            if v and v in raw:
                idx, cnt = raw.find(v), raw.count(v)
                if best is None or cnt < best[0]:
                    best = (cnt, idx)
        if best:
            st = max(0, best[1] - arm_b.WINDOW_BEFORE)
            cands.append((-window_score(st, st + arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER),
                          best[0], 2, best[1], tok))
    if not cands:
        window = raw[:arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER]
        return {"path": path, "window": window,
                "method": why + "; head (no in-file anchor; first "
                          + str(len(window)) + " chars)",
                "anchor_kind": "head", "anchor": "-", "anchor_offset": 0}
    cands.sort(key=lambda t: (t[0], t[1], t[2], t[3]))
    _negscore, cnt, rank, idx, disp = cands[0]
    start = max(0, idx - arm_b.WINDOW_BEFORE)
    window = raw[start:start + arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER]
    return {"path": path, "window": window,
            "method": (why + "; anchor '" + disp + "' at offset " + str(idx)
                       + ", window chars " + str(start) + "-" + str(start + len(window))),
            "anchor_kind": ("hex", "number", "token")[rank],
            "anchor": disp, "anchor_offset": idx}


def results_convention_section(path):
    """The results-file convention section: this repo's sealed results JSONs
    carry their aggregates + verdict at the tail (e_q13/e_q14/e_q15) or a
    *Verdict block mid-file (e_q2's summary). Window around the LAST
    verdict-ish key; else the tail for files under RESULTS_TAIL_MAX. None
    of this is a hand map -- it is the outputs convention the registry
    regenerates every round."""
    if path not in repo_texts() or not path.startswith("experiments/outputs/"):
        return None
    if not (path.endswith("_results.json") or path.endswith("results.json")):
        return None
    raw = repo_texts()[path]
    if len(raw) <= WHOLE_FILE_MAX:
        return None  # whole-file section already carries everything
    hits = [m.start() for m in re.finditer(r"[Vv]erdict", raw)]
    if hits:
        idx = hits[-1]
        start = max(0, idx - arm_b.WINDOW_BEFORE)
        window = raw[start:start + arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER]
        return {"path": path, "window": window,
                "method": "results-file convention: window on the sealed verdict block (offset " + str(idx) + ")",
                "anchor_kind": "verdict-block", "anchor": "verdict", "anchor_offset": idx}
    if len(raw) <= RESULTS_TAIL_MAX:
        window = raw[-(arm_b.WINDOW_BEFORE + arm_b.WINDOW_AFTER):]
        return {"path": path, "window": window,
                "method": "results-file convention: aggregates tail (last " + str(len(window)) + " chars)",
                "anchor_kind": "tail", "anchor": "tail", "anchor_offset": max(0, len(raw) - arm_b.WINDOW_AFTER)}
    return None


def rare_token_file(anchors, seen):
    """Best unseen repo file by distinct-rare-token overlap (>= 2 tokens,
    each with repo-wide count <= RARE_TOKEN_MAX_TOTAL)."""
    rare = []
    for tok in anchors.get("tokens") or []:
        total, _per = needle_hits(tok)
        if 0 < total <= RARE_TOKEN_MAX_TOTAL:
            rare.append((total, tok))
    rare.sort()
    rare = [t for _, t in rare[:14]]
    best = None
    for rel, raw in repo_texts().items():
        if rel in seen:
            continue
        score = 0
        for t in rare:
            if (t in raw or t.replace("-", "_") in raw
                    or t.replace("_", "-") in raw):
                score += 1
        if score >= 2 and (best is None or score > best[1]
                           or (score == best[1] and rel < best[0])):
            best = (rel, score)
    return best


