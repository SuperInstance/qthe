_REPO_TEXTS = None       # {relpath: text} cache
_NEEDLE_MEMO = {}        # needle -> (total_count, [(count, rel, first_idx)])


def repo_texts():
    global _REPO_TEXTS
    if _REPO_TEXTS is None:
        cache = {}
        for p in REPO.rglob("*"):
            if not p.is_file():
                continue
            rel = p.relative_to(REPO)
            if _skip_rel(str(rel)):
                continue
            try:
                cache[str(rel)] = p.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
        _REPO_TEXTS = cache
    return _REPO_TEXTS


def needle_hits(needle):
    """Repo-wide (total_count, [(count, rel, first_idx)]) with memo."""
    if needle not in _NEEDLE_MEMO:
        per = []
        total = 0
        for rel, raw in repo_texts().items():
            c = raw.count(needle)
            if c:
                total += c
                per.append((c, rel, raw.find(needle)))
        _NEEDLE_MEMO[needle] = (total, per)
    return _NEEDLE_MEMO[needle]


