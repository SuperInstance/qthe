def locate_finding(claim, mech):
    """The LAYERED LOCATOR (v3; see module docstring). Returns up to
    MAX_SECTIONS sections or None. Anchors come from the CLAIM PROPER
    (artifact + finding fields) -- the falsifier and fix_sketch are the
    seat's proposals, and their vocabulary is not an artifact claim to
    locate (the mechanical pass still checks them: flags, paths, numbers)."""
    anchors = arm_b.extract_anchors(claim)
    anchors["paths"] = clean_paths(claim, anchors["paths"])
    cited = arm_b.cited_existing_files(anchors["paths"],
                                       anchors.get("barenames") or [])
    sections, seen = [], set()

    def add(path, why):
        if path and path not in seen and path in repo_texts():
            sections.append(section_for(path, anchors, why))
            seen.add(path)

    def add_with_convention(path, why):
        """add() + the results-file convention section (sealed verdict block
        / aggregates tail) when the anchor window missed it."""
        if not (path and path not in seen and path in repo_texts()):
            return
        add(path, why)
        conv = results_convention_section(path)
        if conv and conv["window"] not in [s["window"] for s in sections]:
            sections.append(conv)

    # layer 1 -- explicit citations (slash paths that exist; bare names by
    # unique tree match -- location only, never a mechanical failure)
    for p in cited[:2]:
        add(p, "explicitly cited file")
    for b in anchors.get("barenames") or []:
        if b in [pathlib.Path(p).name for p in seen]:
            continue
        hits = [rel for rel in repo_texts() if pathlib.Path(rel).name == b]
        if len(hits) == 1:
            add(hits[0], "bare name '" + b + "' (unique tree match)")
    # layer 1b -- cited directories: locate their registration/readme/provenance
    for d in dir_citations(claim):
        try:
            entries = sorted(x.name for x in (REPO / d).iterdir() if x.is_file())
        except OSError:
            continue
        for name in entries:
            if name.split(".")[0].upper() in ("README", "REGISTRATION",
                                               "PROVENANCE", "FINDINGS"):
                add(d + name, "cited directory " + d + " registration/readme")
                break
    # layer 2 -- experiment ids via the outputs/receipts naming convention
    for n in eq_ids_in(claim)[:3]:
        for p in files_for_eq(n)[:2]:
            add_with_convention(p, "cited experiment E-Q" + str(n))
    # layer 3 -- claim ids via the stone chain headers' own wiring
    cmap = chain_claim_map()
    for tok in claim_ids_in(claim):
        n = cmap.get(tok)
        if n is None and tok.endswith("'"):
            n = cmap.get(tok[:-1])
        if n is not None:
            for p in files_for_eq(n)[:2]:
                add_with_convention(p, "claim " + tok + " -> stone-chain header -> E-Q" + str(n))
    # layer 4 -- rare-token overlap retrieval
    if len(sections) < 2:
        best = rare_token_file(anchors, seen)
        if best:
            add(best[0], "rare-token retrieval (" + str(best[1])
                + " distinct rare tokens)")
    return sections[:MAX_SECTIONS] or None


