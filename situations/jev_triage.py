    if a.get("numbers"):
        bits.append("numbers [" + ", ".join(a["numbers"][:8]) + "]")
    if a.get("paths"):
        bits.append("cited paths [" + ", ".join(a["paths"][:6]) + "]")
    if a.get("rowofs"):
        bits.append("row refs [" + "; ".join(str(n) + " of " + f for n, f in a["rowofs"][:4]) + "]")
    if a.get("hexes"):
        bits.append("shas [" + ", ".join(h[:12] + "..." for h in a["hexes"][:4]) + "]")
    if not bits:
        return "no mechanically-extractable quoted facts (judge the mechanism only)"
    return "; ".join(bits)


