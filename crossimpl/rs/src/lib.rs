//! # qthe — the Rust port of the qthe reference kernel
//!
//! Fourth cross-implementation (ORCH-R20, lane T11-a), byte-exact against the
//! sealed conformance fixtures on BOTH planes:
//!
//! * **float plane** — byte-identical to `qthe.mjs` (the reference kernel):
//!   σ travels as IEEE754 bit patterns, `term = resonance · σ` is one
//!   correctly-rounded multiply, consumed only through its sign.
//! * **fixed plane (R8)** — byte-identical to `fixedpoint/qthe_fixed.mjs`:
//!   σ_q is an integer in S-units (S = 2³²), `term_q = resonance · σ_q`,
//!   `pressure = acc·S + term_q`. No floats anywhere on this plane.
//!
//! The port mirrors the C99 lane (`crossimpl/c/`) methodology exactly; the
//! conformance battery lives in `src/bin/conformance.rs` and replays
//! `crossimpl/c/fixtures.txt` (generated by executing the JS reference
//! kernels — never this crate).
//!
//! ## The primitive (SPEC.md §"The primitive", LAYER 0)
//!
//! One byte, two planes — data is geometry, control is physics:
//!
//! ```text
//! bit:   7  6  5 4 3 2 1 0
//!        [τ:2][  d:6        ]
//! ```
//!
//! * `d = c & 0x3F` — the spatial-amplitude coordinate, `[0, 63]`
//! * `τ = c >> 6` — the timbre / operator state, `{0, 1, 2, 3}`
//!
//! | τ | name    | operator Ψ(τ) | substrate action |
//! |---|---------|---------------|------------------|
//! | 0 | Ground  | `0`           | static anchor |
//! | 1 | Attract | `+1`          | forward cascade |
//! | 2 | Repel   | `−1`          | inversion layer |
//! | 3 | Abstain | `i`           | the Looking Glass — bridges via the wormhole table |
//!
//! ## Interpretation receipts honored (qthe.mjs header, R1–R8)
//!
//! * **R1** edges are TOROIDAL (Moore-8 wraps; every cell has exactly 8
//!   neighbor slots — see `AMBIGUITY.md` A-R2 for the degenerate-dimension
//!   reading where the slots are not 8 distinct cells).
//! * **R2** neighbors are read from the PRE-tick snapshot (synchronous
//!   double-buffered update); the wormhole table is read LIVE in row-major
//!   cell order (same-tick writes are audible to later readers).
//! * **R3** Abstain cells still accumulate the real neighborhood acc; on a
//!   twin hit the imaginary term `resonance·σ` is added to the pressure whose
//!   SIGN moves `d` (the data rule table is untouched).
//! * **R4** wormhole WRITES are last-writer-wins per slot; a cell never
//!   resonates with its own write (guard: different (x,y) AND resonance ≠ 0).
//! * **R6** the substrate carries dims + tick counter + lazy wormhole table;
//!   tick mutates in place.
//! * **R8** the fixed plane's scaled domain: `pressure = acc·S + term_q`.
//! * **σ never comes from a transcendental evaluation.** `log₂(3)` is the
//!   exact bit constant `0x3FF95C01A39FBD68` (receipted from the JS
//!   reference); 2/3 is `0x3FE5555555555555`. Rust `f64` multiply/add are
//!   IEEE754 correctly-rounded on every platform, so term bits agree; a
//!   `log2()` call is not correctly-rounded-guaranteed and is never made.
//!
//! Zero dependencies: std only.

#![forbid(unsafe_code)]

// ── LAYER 0 · the primitive (SPEC.md §LAYER 0) ─────────────────────────────

/// Low 6 bits: the spatial-amplitude coordinate mask (SPEC: `d = c & 0x3F`).
pub const D_MAX: u8 = 63;
/// The 64-slot wormhole table (SPEC LAYER 1 item 4).
pub const SLOT_COUNT: usize = 64;

/// Timbre values (SPEC §"The primitive" table).
pub mod tau {
    /// τ=0 Ground — Ψ = 0, contributes to neither channel.
    pub const GROUND: u8 = 0;
    /// τ=1 Attract — Ψ = +1, real channel, positive.
    pub const ATTRACT: u8 = 1;
    /// τ=2 Repel — Ψ = −1, real channel, negative.
    pub const REPEL: u8 = 2;
    /// τ=3 Abstain — Ψ = i, the Looking Glass (imaginary channel).
    pub const ABSTAIN: u8 = 3;
}

/// `log₂(3)` as exact IEEE754 bits — the lazy default σ of the float plane.
/// Taken from the JS reference kernel's `Math.log2(3)` (receipted in the C
/// lane's `qthe_core.h`); NEVER recompute at runtime (the σ-as-bits law).
pub const SIGMA_LOG2_3_BITS: u64 = 0x3FF9_5C01_A39F_BD68;

/// The float-plane default σ (log₂ 3) as an `f64`, from bits only.
pub const DEFAULT_SIGMA: f64 = f64::from_bits(SIGMA_LOG2_3_BITS);

/// The fixed-plane default σ_q (R8): `round(log₂(3) · 2³²) = 6807362106`,
/// baked as an integer literal exactly like `qthe_fixed.mjs`
/// (`DEFAULT_SIGMA_Q`). Derivations live in that file's header.
pub const DEFAULT_SIGMA_Q: u64 = 6_807_362_106;

/// The fixed-point scale S = 2³² (R8: σ_q lives in Q(n,32)).
pub const SCALE: i64 = 4_294_967_296;

/// Pack: `(τ, d) → c`, the implied inverse of the SPEC's unpack
/// (SPEC LAYER 0 item 1; AMBIGUITY.md A1). Out-of-range inputs are masked,
/// mirroring the JS kernel (`((tau & 3) << 6) | (d & 63)`).
#[inline]
pub fn pack(tau: u8, d: u8) -> u8 {
    ((tau & 3) << 6) | (d & D_MAX)
}

/// τ of a packed cell: bits 7-6 (SPEC: `τ = c >> 6`).
#[inline]
pub fn tau_of(c: u8) -> u8 {
    (c >> 6) & 3
}

/// d of a packed cell: bits 5-0 (SPEC: `d = c & 0x3F`).
#[inline]
pub fn d_of(c: u8) -> u8 {
    c & D_MAX
}

/// Unpack: `c → (τ, d)` — bijection onto `{0..3} × {0..63}` (LAYER 0 item 1).
#[inline]
pub fn unpack(c: u8) -> (u8, u8) {
    (tau_of(c), d_of(c))
}

/// Ψ(τ) as exact-integer CHANNEL COEFFICIENTS `(real, imag)` — the reading
/// the SPEC's own channel expansion fixes (LAYER 0 item 3):
/// Ground → (0,0), Attract → (+1,0), Repel → (−1,0), Abstain → (0,+1).
///
/// The JS kernel's `PSI` literal is `[0, 1, -1, 'i']` — the operator
/// CHARACTER `'i'` is notation, never multiplied in (AMBIGUITY.md A2).
#[inline]
pub fn psi_channels(tau: u8) -> (i64, i64) {
    match tau & 3 {
        0 => (0, 0),
        1 => (1, 0),
        2 => (-1, 0),
        _ => (0, 1),
    }
}

/// Split-channel vector pass (SPEC LAYER 0 item 3), EXACT integers:
///
/// ```text
/// y_j^R = Σ_{τ=1} d·x_k  −  Σ_{τ=2} d·x_k      (real channel)
/// y_j^I = Σ_{τ=3} d·x_k                          (imaginary channel)
/// ```
///
/// Ground (τ=0) contributes to neither channel even when d>0. `weights` is a
/// row-major J×K matrix of packed QTHE bytes; `xs` are the K integer inputs.
/// Returns `(re, im)`, each of length J.
///
/// Carrier: `i64` (exact for all battery sizes). The JS reference
/// accumulates in integer-exact IEEE754 doubles (exact ≤ 2⁵³ — the py lane's
/// finding F1 horizon); over the specified battery surface the two carriers
/// agree on every value.
///
/// Ragged shapes are INVALID on the specified surface (AMBIGUITY.md A3/F2:
/// the JS kernel silently NaNs on a row longer than `xs`); this port
/// panics loudly instead of inventing data.
pub fn vector_pass(weights: &[u8], rows: usize, cols: usize, xs: &[i64]) -> (Vec<i64>, Vec<i64>) {
    assert_eq!(
        weights.len(),
        rows * cols,
        "vector_pass: weights must be exactly rows*cols (ragged input is invalid)"
    );
    assert!(
        xs.len() >= cols || cols == 0,
        "vector_pass: xs shorter than cols (ragged input is invalid)"
    );
    let mut re = Vec::with_capacity(rows);
    let mut im = Vec::with_capacity(rows);
    for j in 0..rows {
        let (mut r, mut m) = (0i64, 0i64);
        for k in 0..cols {
            let c = weights[j * cols + k];
            let dv = (d_of(c)) as i64;
            let x = xs[k];
            match tau_of(c) {
                1 => r += dv * x, // Attract: +d·x into the real channel
                2 => r -= dv * x, // Repel:   −d·x into the real channel
                3 => m += dv * x, // Abstain: +d·x into the imaginary channel
                _ => {}           // Ground: neither channel
            }
        }
        re.push(r);
        im.push(m);
    }
    (re, im)
}

// ── LAYER 1 · item 4 — the 64-slot wormhole table ──────────────────────────

/// A twin-resonance event emitted by [`tick`] (the kernel's telemetry; the
/// SPEC is silent on the event shape — crossimpl/AMBIGUITY.md A-R1).
///
/// Float plane: `term = resonance · σ` (a double, compared as BITS).
/// Fixed plane (R8): `term_q = resonance · σ_q` (an integer in S-units —
/// the float plane's `term·S` up to the R8 quantization band).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Event {
    /// 1-based tick index at emission.
    pub tick: i32,
    /// x of the resonating Abstain cell.
    pub x: i32,
    /// y of the resonating Abstain cell.
    pub y: i32,
    /// the wormhole slot (= the cell's d).
    pub slot: i32,
    /// the resonance read from the slot (|acc|+1 of the earlier writer).
    pub resonance: i32,
    /// float-plane term `resonance · σ` (bit-exact vs qthe.mjs).
    pub term: f64,
    /// fixed-plane term `resonance · σ_q` in S-units (R8).
    pub term_q: u64,
}

/// The 64-slot wormhole table (SPEC LAYER 1 item 4 — the compile-time
/// blueprint: static declarative allocation, zero runtime discovery).
///
/// Slot s is empty or `(x, y, resonance)`. Reads are LIVE (R2); writes are
/// last-writer-wins per slot (R4). The table persists across ticks.
///
/// DERIVATION NOTE (the task's "compile it exactly as qthe.mjs does"):
/// `qthe.mjs` does not ship a table of constants — the table starts EMPTY
/// (`sx/sy` filled with −1, `sr` zero, `occupied` zero, `totalWrites` 0) and
/// is populated at tick time by Abstain writers. This port mirrors that
/// derivation verbatim: same 64 slots, same −1/0 initial state, same
/// live-read/LWW mechanics, same `totalWrites` counter.
#[derive(Debug, Clone)]
pub struct WormholeTable {
    /// float-plane σ (never evaluated from a transcendental — bits only).
    pub sigma: f64,
    /// fixed-plane σ_q in S-units (R8); used when `use_fixed`.
    pub sigma_q: u64,
    /// select the fixed plane (R8) for this table.
    pub use_fixed: bool,
    sx: [i32; SLOT_COUNT],
    sy: [i32; SLOT_COUNT],
    sr: [i32; SLOT_COUNT],
    occupied: [bool; SLOT_COUNT],
    /// cumulative writes, deterministic (mirrors `totalWrites`).
    pub total_writes: u64,
}

impl WormholeTable {
    /// A float-plane table with the given σ (pass bits through
    /// `f64::from_bits`, never a runtime `log2`).
    pub fn new(sigma: f64) -> Self {
        WormholeTable {
            sigma,
            sigma_q: 0,
            use_fixed: false,
            sx: [-1; SLOT_COUNT],
            sy: [-1; SLOT_COUNT],
            sr: [0; SLOT_COUNT],
            occupied: [false; SLOT_COUNT],
            total_writes: 0,
        }
    }

    /// A fixed-plane table (R8) with σ_q in S-units.
    pub fn new_fixed(sigma_q: u64) -> Self {
        WormholeTable {
            sigma: 0.0,
            sigma_q,
            use_fixed: true,
            sx: [-1; SLOT_COUNT],
            sy: [-1; SLOT_COUNT],
            sr: [0; SLOT_COUNT],
            occupied: [false; SLOT_COUNT],
            total_writes: 0,
        }
    }

    /// The float-plane default table (σ = log₂(3), from bits).
    pub fn default_float() -> Self {
        WormholeTable::new(DEFAULT_SIGMA)
    }

    /// The fixed-plane default table (σ_q = 6807362106, baked integer).
    pub fn default_fixed() -> Self {
        WormholeTable::new_fixed(DEFAULT_SIGMA_Q)
    }

    /// Reset to the empty state (mirrors `clear()`).
    pub fn clear(&mut self) {
        self.sx = [-1; SLOT_COUNT];
        self.sy = [-1; SLOT_COUNT];
        self.sr = [0; SLOT_COUNT];
        self.occupied = [false; SLOT_COUNT];
        self.total_writes = 0;
    }

    /// LIVE read (R2): `None` when the slot is out of range or empty.
    #[inline]
    pub fn read(&self, slot: usize) -> Option<(i32, i32, i32)> {
        if slot < SLOT_COUNT && self.occupied[slot] {
            Some((self.sx[slot], self.sy[slot], self.sr[slot]))
        } else {
            None
        }
    }

    /// LWW write (R4): one occupant per slot; bumps `total_writes`.
    #[inline]
    pub fn write(&mut self, slot: usize, x: i32, y: i32, resonance: i32) {
        assert!(slot < SLOT_COUNT, "wormhole slot out of range: {slot}");
        self.sx[slot] = x;
        self.sy[slot] = y;
        self.sr[slot] = resonance;
        self.occupied[slot] = true;
        self.total_writes += 1;
    }

    /// Number of occupied slots (mirrors `occupiedCount()`).
    pub fn occupied_count(&self) -> usize {
        self.occupied.iter().filter(|&&o| o).count()
    }
}

// ── LAYER 1 · item 5 — substrate + Moore-8 tick ────────────────────────────

/// The substrate: `w·h` packed cells, row-major, plus dims, tick counter and
/// the lazy-owned wormhole table (R6: state rides on the substrate).
#[derive(Debug, Clone)]
pub struct Substrate {
    /// width (x extent)
    pub w: i32,
    /// height (y extent)
    pub h: i32,
    /// tick counter (advanced once per [`tick`])
    pub ticks: i64,
    /// the packed byte plane, row-major (`cells[y*w + x]`)
    pub cells: Vec<u8>,
    /// lazy-owned persistent wormhole table (created on first wormhole tick)
    pub wh: Option<WormholeTable>,
}

impl Substrate {
    /// Build a substrate from an initial plane (row-major `w·h` bytes).
    /// Mirrors `makeSubstrate` (dims validated positive; plane copied).
    pub fn new(w: i32, h: i32, init_plane: &[u8]) -> Substrate {
        assert!(w >= 1 && h >= 1, "substrate dimensions must be positive integers");
        let n = (w as usize) * (h as usize);
        assert_eq!(init_plane.len(), n, "init plane must be exactly w*h bytes");
        Substrate {
            w,
            h,
            ticks: 0,
            cells: init_plane.to_vec(),
            wh: None,
        }
    }

    /// The canonical plane hash (matches `experiments/_harness.mjs`
    /// `planeHash`): sha256 over `"{w}x{h}@t={t}:{lowercase hex of the byte
    /// plane}"`. The imaginary plane is never hashed.
    pub fn plane_hash(&self, t_override: i64) -> String {
        let t = if t_override >= 0 { t_override } else { self.ticks };
        let mut buf = String::with_capacity(32 + 2 * self.cells.len());
        buf.push_str(&format!("{}x{}@t={}:", self.w, self.h, t));
        const HEX: &[u8; 16] = b"0123456789abcdef";
        for &b in &self.cells {
            buf.push(HEX[(b >> 4) as usize] as char);
            buf.push(HEX[(b & 15) as usize] as char);
        }
        let digest = sha256(buf.as_bytes());
        let mut out = String::with_capacity(64);
        for byte in digest {
            out.push_str(&format!("{byte:02x}"));
        }
        out
    }
}

/// THE rule table (SPEC LAYER 1 item 5), float-plane pressure: net-positive
/// → d toward saturation `min(d+1, 63)`; net-negative → toward 0; zero →
/// unchanged. τ NEVER changes here (timbre is written only by injectors).
#[inline]
fn next_d(d: u8, pressure: f64) -> u8 {
    if pressure > 0.0 {
        if d < D_MAX { d + 1 } else { D_MAX }
    } else if pressure < 0.0 {
        if d > 0 { d - 1 } else { 0 }
    } else {
        d
    }
}

/// THE rule table, fixed-plane pressure (R8, i64 in S-units) — identical
/// shape; only the sign is consumed.
#[inline]
fn next_d_q(d: u8, pressure: i64) -> u8 {
    if pressure > 0 {
        if d < D_MAX { d + 1 } else { D_MAX }
    } else if pressure < 0 {
        if d > 0 { d - 1 } else { 0 }
    } else {
        d
    }
}

/// One synchronous Moore-8 tick — the shared implementation for both planes.
///
/// * `wormholes == false` → the table is never touched (the paired OFF arm).
/// * `sigma` (float plane): per-tick σ override, as BITS (None = the table's
///   own / the lazy default log₂(3)).
/// * `sigma_q_override` (fixed plane): per-tick σ_q in S-units (0 = the
///   table's own / the lazy default 6807362106).
///
/// Mutates the substrate in place (R6) and appends twin events to `events`.
/// Returns the number of events emitted this tick.
fn tick_impl(
    s: &mut Substrate,
    wormholes: bool,
    sigma: Option<f64>,
    sigma_q_override: u64,
    use_fixed: bool,
    events: &mut Vec<Event>,
) -> usize {
    let w = s.w;
    let h = s.h;
    let nev0 = events.len();

    // Lazy table creation (mirrors the JS kernel's `cells.__wormholes`).
    if wormholes && s.wh.is_none() {
        s.wh = Some(if use_fixed {
            WormholeTable::new_fixed(if sigma_q_override != 0 {
                sigma_q_override
            } else {
                DEFAULT_SIGMA_Q
            })
        } else {
            WormholeTable::new(sigma.unwrap_or(DEFAULT_SIGMA))
        });
    }

    // σ resolution per plane (mirrors the JS precedence: opts override wins,
    // then the table's own, then the default).
    let sigma_f = match sigma {
        Some(v) => v,
        None => match &s.wh {
            Some(t) if !use_fixed => t.sigma,
            _ => DEFAULT_SIGMA,
        },
    };
    let sigma_q = if sigma_q_override != 0 {
        sigma_q_override
    } else {
        match &s.wh {
            Some(t) => t.sigma_q,
            None => 0,
        }
    };

    // Pre-tick neighbor snapshot (R2: synchronous update). The JS kernel
    // reuses a `__scratch` buffer; here the snapshot is a per-tick clone —
    // behaviorally identical (the snapshot is never aliased after the tick).
    let snap = s.cells.clone();
    let tick_no = (s.ticks + 1) as i32;

    for y in 0..h {
        let y_up = (y + h - 1) % h;
        let y_dn = (y + 1) % h;
        for x in 0..w {
            let i = (y * w + x) as usize;
            let c = snap[i];
            let tau = tau_of(c);
            let d = d_of(c);

            // Real accumulator over Moore-8 (pre-tick grid, R2):
            // Attract +d, Repel −d; the center cell never contributes.
            let x_l = (x + w - 1) % w;
            let x_r = (x + 1) % w;
            let mut acc: i64 = 0;
            for ny in [y_up, y, y_dn] {
                for nx in [x_l, x, x_r] {
                    if ny == y && nx == x {
                        continue; // Moore-8: the 8 neighbors, never the center
                    }
                    let nc = snap[(ny * w + nx) as usize];
                    match tau_of(nc) {
                        1 => acc += d_of(nc) as i64,
                        2 => acc -= d_of(nc) as i64,
                        _ => {}
                    }
                }
            }

            if use_fixed {
                // ── fixed plane (R8): pressure in S-units ──
                let mut pressure = acc;
                if tau == tau::ABSTAIN && wormholes {
                    if let Some(table) = s.wh.as_mut() {
                        if let Some((hx, hy, res)) = table.read(d as usize) {
                            if res != 0 && (hx != x || hy != y) {
                                let term_q = res as u64 * sigma_q;
                                // R8 scaled domain (qthe_fixed.mjs:308):
                                pressure = acc * SCALE + term_q as i64;
                                events.push(Event {
                                    tick: tick_no,
                                    x,
                                    y,
                                    slot: d as i32,
                                    resonance: res,
                                    term: 0.0,
                                    term_q,
                                });
                            }
                        }
                        table.write(
                            d as usize,
                            x,
                            y,
                            (if acc < 0 { -acc } else { acc }) as i32 + 1,
                        );
                    }
                }
                let nd = next_d_q(d, pressure);
                s.cells[i] = (tau << 6) | nd;
            } else {
                // ── float plane: pressure as f64, sign-only consumption ──
                let mut pressure = acc as f64;
                if tau == tau::ABSTAIN && wormholes {
                    if let Some(table) = s.wh.as_mut() {
                        if let Some((hx, hy, res)) = table.read(d as usize) {
                            if res != 0 && (hx != x || hy != y) {
                                // ONE correctly-rounded multiply — bit-exact
                                // vs the JS kernel's `resonance * sigma`.
                                let term = res as f64 * sigma_f;
                                pressure = acc as f64 + term;
                                events.push(Event {
                                    tick: tick_no,
                                    x,
                                    y,
                                    slot: d as i32,
                                    resonance: res,
                                    term,
                                    term_q: 0,
                                });
                            }
                        }
                        table.write(
                            d as usize,
                            x,
                            y,
                            (if acc < 0 { -acc } else { acc }) as i32 + 1,
                        );
                    }
                }
                let nd = next_d(d, pressure);
                s.cells[i] = (tau << 6) | nd;
            }
        }
    }
    s.ticks += 1;
    events.len() - nev0
}

/// One synchronous Moore-8 tick, FLOAT plane (byte-identical to `qthe.mjs`).
/// Appends twin events to `events`; returns the count emitted this tick.
pub fn tick(s: &mut Substrate, wormholes: bool, sigma: Option<f64>, events: &mut Vec<Event>) -> usize {
    tick_impl(s, wormholes, sigma, 0, false, events)
}

/// One synchronous Moore-8 tick, FIXED plane (R8; byte-identical to
/// `fixedpoint/qthe_fixed.mjs`). Pass `sigma_q = 0` to use the table's own.
pub fn tick_fixed(s: &mut Substrate, wormholes: bool, sigma_q: u64, events: &mut Vec<Event>) -> usize {
    tick_impl(s, wormholes, None, sigma_q, true, events)
}

/// The kernel's coupled twin pressure in S-units (R8):
/// `acc·S + (|acc|+1)·σ_q` — exported so audits recompute the kernel's
/// ACTUAL arithmetic, not a copy (mirrors `twinPressureQ`).
pub fn twin_pressure_q(acc: i64, sigma_q: u64) -> i64 {
    acc * SCALE + (acc.abs() + 1) as i64 * sigma_q as i64
}

// ── seeded randomness (callers only, never inside tick) ────────────────────

/// mulberry32 — SEEDED PRNG for CALLERS (substrate seeding, probes; mirrors
/// `qthe.mjs`). NEVER called inside [`tick`]; the kernel's determinism does
/// not depend on it. Exact u32 semantics (wrapping ops ≙ JS `Math.imul` /
/// `>>>`).
#[derive(Debug, Clone)]
pub struct Rng {
    state: u32,
}

impl Rng {
    /// Seed the generator (any u32; JS `seed >>> 0`).
    pub fn new(seed: u32) -> Rng {
        Rng { state: seed }
    }

    /// Raw 32-bit draw (exact mulberry32 recurrence).
    pub fn next_u32(&mut self) -> u32 {
        let a = self.state.wrapping_add(0x6d2b_79f5);
        self.state = a;
        let mut t = a;
        t = (t ^ (t >> 15)).wrapping_mul(t | 1);
        t ^= t.wrapping_add((t ^ (t >> 7)).wrapping_mul(t | 61));
        t ^ (t >> 14)
    }

    /// `[0, 1)` draw (mirrors `((t ^ (t >>> 14)) >>> 0) / 4294967296`).
    pub fn next_f64(&mut self) -> f64 {
        self.next_u32() as f64 / 4_294_967_296.0
    }
}

