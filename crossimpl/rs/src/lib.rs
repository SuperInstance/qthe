fn sha_compress(block: &[u8], h: &mut [u32; 8]) {
    let mut w = [0u32; 64];
    for i in 0..16 {
        w[i] = (block[i * 4] as u32) << 24
            | (block[i * 4 + 1] as u32) << 16
            | (block[i * 4 + 2] as u32) << 8
            | (block[i * 4 + 3] as u32);
    }
    for i in 16..64 {
        let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
        let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16]
            .wrapping_add(s0)
            .wrapping_add(w[i - 7])
            .wrapping_add(s1);
    }
    let (mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh) =
        (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
    for i in 0..64 {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let ch = (e & f) ^ (!e & g);
        let t1 = hh
            .wrapping_add(s1)
            .wrapping_add(ch)
            .wrapping_add(SHA_K[i])
            .wrapping_add(w[i]);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let maj = (a & b) ^ (a & c) ^ (b & c);
        let t2 = s0.wrapping_add(maj);
        hh = g;
        g = f;
        f = e;
        e = d.wrapping_add(t1);
        d = c;
        c = b;
        b = a;
        a = t1.wrapping_add(t2);
    }
    h[0] = h[0].wrapping_add(a);
    h[1] = h[1].wrapping_add(b);
    h[2] = h[2].wrapping_add(c);
    h[3] = h[3].wrapping_add(d);
    h[4] = h[4].wrapping_add(e);
    h[5] = h[5].wrapping_add(f);
    h[6] = h[6].wrapping_add(g);
    h[7] = h[7].wrapping_add(hh);
}

/// Raw sha256 (FIPS 180-4). Exposed for KATs; the canonical plane hash uses it.
pub fn sha256(data: &[u8]) -> [u8; 32] {
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];
    let full = data.len() / 64;
    for b in 0..full {
        sha_compress(&data[b * 64..b * 64 + 64], &mut h);
    }
    let rem = data.len() - full * 64;
    let mut block = [0u8; 64];
    block[..rem].copy_from_slice(&data[full * 64..]);
    block[rem] = 0x80;
    if rem >= 56 {
        sha_compress(&block, &mut h);
        block = [0u8; 64];
    }
    let bits = (data.len() as u64) * 8;
    for i in 0..8 {
        block[56 + i] = (bits >> (56 - 8 * i)) as u8;
    }
    sha_compress(&block, &mut h);
    let mut out = [0u8; 32];
    for i in 0..8 {
        out[i * 4] = (h[i] >> 24) as u8;
        out[i * 4 + 1] = (h[i] >> 16) as u8;
        out[i * 4 + 2] = (h[i] >> 8) as u8;
        out[i * 4 + 3] = h[i] as u8;
    }
    out
}

