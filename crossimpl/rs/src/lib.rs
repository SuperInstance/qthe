    #[test]
    fn wormhole_live_read_and_never_self() {
        // R2/R4: two Abstain cells with the same d, far apart. Tick 1: the
        // row-major-EARLIER writer (1,1) writes slot 20 first; the later
        // reader (6,6) hits it THE SAME TICK (live read) — but (1,1) itself
        // resonated with nothing (slot was empty when it read). Tick 2:
        // (1,1) now reads the standing write left by (6,6)'s tick-1 write
        // (LWW) and resonates in turn. Neither ever self-resonates.
        let mut plane = vec![0u8; 8 * 8];
        plane[(1 * 8 + 1) as usize] = pack(tau::ABSTAIN, 20); // (x=1, y=1) first in row-major
        plane[(6 * 8 + 6) as usize] = pack(tau::ABSTAIN, 20); // (x=6, y=6)
        let mut s = Substrate::new(8, 8, &plane);
        let mut ev = Vec::new();
        let n1 = tick(&mut s, true, None, &mut ev);
        assert_eq!(n1, 1, "same-tick live read: the later co-tick writer hits the earlier's fresh write");
        assert_eq!((ev[0].x, ev[0].y, ev[0].slot, ev[0].resonance), (6, 6, 20, 1));
        let table = s.wh.as_ref().unwrap();
        assert_eq!(table.occupied_count(), 1, "same slot d=20 — one occupant (LWW)");
        assert_eq!(table.total_writes, 2);
        // (6,6) ascended (pressure = 1·log2(3) > 0), (1,1) held (no hit).
        assert_eq!(d_of(s.cells[(6 * 8 + 6) as usize]), 21);
        assert_eq!(d_of(s.cells[(1 * 8 + 1) as usize]), 20);
        // Tick 2: (6,6) now carries d=21 (writes slot 21); (1,1) still d=20
        // reads slot 20 = (6,6)'s standing tick-1 write → its turn to ring.
        let before = ev.len();
        tick(&mut s, true, None, &mut ev);
        let new: Vec<&Event> = ev[before..].iter().collect();
        assert_eq!(new.len(), 1);
        assert_eq!((new[0].x, new[0].y, new[0].slot), (1, 1, 20));
        // term = resonance · log2(3) — ONE multiply, bit-comparable.
        assert_eq!(new[0].term.to_bits(), DEFAULT_SIGMA.to_bits());
        // The OFF arm never touches the table.
        let mut off = Substrate::new(8, 8, &plane);
        let mut ev2 = Vec::new();
        tick(&mut off, false, None, &mut ev2);
        assert!(off.wh.is_none() && ev2.is_empty());
    }

